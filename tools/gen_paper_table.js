// Regenerates the paper index in README.md / README_CN.md from data/papers.json.
// Papers carrying a `card` field render as GPT-3-baseline improvement cards;
// the rest fall back to the migration table until all cards are written.
// Usage: node tools/gen_paper_table.js   (run from the repo root)
const fs=require('fs');
const path=require('path');
const ROOT=path.join(__dirname,'..');
const DB=JSON.parse(fs.readFileSync(path.join(ROOT,'data','papers.json'),'utf8'));

const SCENE_ORDER=['policy','action','reward','skill','constraint','world','design','reasoning','agentself','research'];
const SCENE_EN={policy:'Policy',action:'Action',reward:'Reward',skill:'Skill',constraint:'Constraint',world:'World',design:'Design',reasoning:'Reasoning',agentself:'Agent-Self',research:'Research'};
const SCENE_CN={policy:'策略',action:'动作',reward:'奖励',skill:'技能',constraint:'约束',world:'世界',design:'设计',reasoning:'推理',agentself:'自我',research:'研究'};
const DIR_EN={oneshot:'One-shot',loop:'Closed-loop',evo:'Evolutionary',skill:'Skill-accrual',multi:'Multi-agent',wm:'World-model',mem:'Memory'};
const DIR_CN={oneshot:'单次生成',loop:'闭环调整',evo:'进化搜索',skill:'技能沉淀',multi:'多智能体',wm:'世界模型',mem:'记忆上下文'};
const LVL_EN={0:'Frozen mechanism',1:'Mechanism self-evolves',2:'Adapts at runtime',3:'Weight training',4:'Recursive self-improvement'};
const LVL_CN={0:'机制冻结',1:'机制自进化',2:'运行时适应',3:'权重训练',4:'递归自我改进'};
const TS_EN={a:'Collects data + trains',b:'Collects data, no training',c:'Trains, no data collection',d:'Frozen at runtime'};
const TS_CN={a:'采集数据＋训练',b:'只采集数据，不训练',c:'只训练，不采集',d:'运行时全冻结'};
const STK_EN={0:'No feedback',1:'Evidence feedback',2:'Verification feedback',3:'Data flywheel'};
const STK_CN={0:'无反馈',1:'证据反馈',2:'验证反馈',3:'数据飞轮'};
const ORA_EN={sym:'Symbolic',sim:'Simulation',model:'Model',real:'Real-world',human:'Human',na:'N/A'};
const ORA_CN={sym:'符号',sim:'仿真',model:'模型',real:'真实环境',human:'人类',na:'不适用'};
const DOM_EN={robot:'Robotics',general:'General',front:'Frontend',swe:'Software',gui:'GUI',mc:'Minecraft',math:'Math',web:'Web',cad:'CAD',onto:'Ontology',drug:'Drug discovery',chip:'Chip',arch:'Architecture',law:'Legal',nlp:'NLP',multimodal:'Multimodal'};
const DOM_CN={robot:'机器人',general:'通用',front:'前端',swe:'软件工程',gui:'图形界面',mc:'Minecraft',math:'数学',web:'网页',cad:'CAD',onto:'本体',drug:'药物研发',chip:'芯片',arch:'体系结构',law:'法律',nlp:'NLP',multimodal:'多模态'};

const esc=s=>String(s||'').replace(/\|/g,'/');
const map=(vals,dic)=>(vals||[]).map(v=>dic[v]||v).join(', ');
const sortPapers=arr=>arr.sort((a,b)=>b.lvl-a.lvl||parseInt(b.id.slice(1))-parseInt(a.id.slice(1)));
const sceneSorted=()=>SCENE_ORDER.flatMap(s=>sortPapers(DB.filter(p=>p.scenes[0]===s)));

const DIMS=[['dir','Direction','方向'],['upd','Update Capability','更新能力'],['rt','Runtime Behavior','运行时行为'],['stk','Feedback Stack','反馈栈'],['self','Improves itself?','自己改自己？']];

function renderCard(p,lang,idx){
  const L=lang==='cn';
  const card=L?p.card:p.card_en;
  const S=L?SCENE_CN:SCENE_EN, O=L?ORA_CN:ORA_EN, M=L?DOM_CN:DOM_EN;
  const th=L?'| tag方向 | 文章中具体设计 | 具体设计带来增益 | 带来增益的原理（第一性解释） |':'| Tag | Design in the paper | Gain from the design | Why the gain happens (first-principles) |';
  const out=[];
  out.push('### '+idx+'. ['+esc(p.n)+']('+esc(p.l)+')');
  out.push('');
  out.push((L?'**场景**：':'**Scene**: ')+map(p.scenes,S)+(L?' ｜ **领域**：':' | **Domain**: ')+(M[p.dom]||p.dom)+(L?' ｜ **Oracle**：':' | **Oracle**: ')+(((p.oracle||[]).length?map(p.oracle,O):O.na)));
  out.push('');
  for(const [key,enLabel,cnLabel] of DIMS){
    const label=L?cnLabel:enLabel;
    const rows=card[key]||[];
    if(!rows.length){
      out.push('**'+label+'**：'+(key==='stk'?(L?'无反馈':'No feedback'):(L?'否':'No')));
      out.push('');
      continue;
    }
    out.push('**'+label+'**');
    out.push('');
    out.push(th);
    out.push('|---|---|---|---|');
    for(const r of rows) out.push('| '+esc(r.t)+' | '+(r.d?esc(r.d):'—')+' | '+(r.g?esc(r.g):'—')+' | '+(r.w?esc(r.w):'—')+' |');
    out.push('');
  }
  if(card.extra){
    out.push((L?'**论文中的其他发现**：':'**Other findings in the paper**: ')+esc(card.extra));
    out.push('');
  }
  out.push('---');
  out.push('');
  return out.join('\n');
}

function build(lang){
  const L=lang==='cn';
  const withCard=sceneSorted().filter(p=>p.card);
  const noCard=sceneSorted().filter(p=>!p.card);
  const lines=[];
  lines.push(L?'<!-- 论文索引（由 tools/gen_paper_table.js 生成，勿手改） -->':'<!-- Paper index (generated by tools/gen_paper_table.js — do not edit by hand) -->');
  lines.push('');
  lines.push(L?
    '本索引的参照基线是**最简 chatbot 问答（GPT-3 模式）**：冻结模型、单轮提示→回答、无工具、无反馈、无记忆。每张卡片回答一个问题——这篇论文相对该基线引入了哪些具体设计，各带来什么增益。五个维度（方向/更新能力/运行时行为/反馈栈/自己改自己？）各一张四列子表：**tag方向**（哪一维）→ **文章中具体设计**（做了什么）→ **具体设计带来增益**（得到什么）→ **带来增益的原理**（为什么会得到，第一性解释）。设计列与增益列尽量**直接引用论文原文**（原句+一句话总结）；**原理列默认为编者推演**（论文很少自解释 why），论文自己给出机理时则引原文。无原文支撑处标「编者按」。维度语义见 [四维分类体系](#四维分类体系) 与 [附加-tag](#附加-tag)。':
    'The reference baseline of this index is the **simplest chatbot Q&A (GPT-3 mode)**: a frozen model, single-turn prompt→answer, no tools, no feedback, no memory. Each card answers one question — what concrete designs the paper introduces over that baseline, and the gain each design brings. The five dimensions (Direction / Update Capability / Runtime Behavior / Feedback Stack / Improves itself?) each get a four-column sub-table: **Tag** (which dimension) → **Design in the paper** (what was done) → **Gain from the design** (what was achieved) → **Why the gain happens** (first-principles explanation). Design and gain cells quote the paper\'s original wording wherever possible (quote + one-line summary); the **why column is editorial by default** (papers rarely explain their own why) and quotes the paper when it does. Editorial inference is marked "编者按"/"editor". See [The Taxonomy](#the-taxonomy) and [Additional Tags](#additional-tags).');
  lines.push('');
  lines.push(L?
    '**进度**：已迁移卡片 '+withCard.length+' 篇 ｜ 待迁移 '+noCard.length+' 篇（暂列下方表格，全部迁移完成后表格自动消失）':
    '**Progress**: '+withCard.length+' papers migrated to cards | '+noCard.length+' pending (listed in the table below until fully migrated)');
  lines.push('');
  let idx=0;
  for(const p of withCard){ idx++; lines.push(renderCard(p,lang,idx)); }
  if(noCard.length){
    lines.push('');
    lines.push(L?'## 待迁移论文表（'+noCard.length+' 篇）':'## Pending Migration Table ('+noCard.length+' papers)');
    lines.push('');
    lines.push(L?'| # | 论文 | 场景 | 方向 | 更新能力 | 运行时行为 | 反馈栈 | Oracle | 领域 | 自己改自己？ |':'| # | Paper | Scene | Direction | Update Capability | Runtime Behavior | Feedback Stack | Oracle | Domain | Improves itself? |');
    lines.push('|'+'---|'.repeat(10));
    const S=L?SCENE_CN:SCENE_EN, D=L?DIR_CN:DIR_EN, V=L?LVL_CN:LVL_EN, T=L?TS_CN:TS_EN, K=L?STK_CN:STK_EN, O=L?ORA_CN:ORA_EN, M=L?DOM_CN:DOM_EN;
    let j=0;
    for(const p of noCard){
      j++;
      lines.push('| '+j+' | ['+esc(p.n)+']('+esc(p.l)+') | '+map(p.scenes,S)+' | '+map(p.dirs,D)+' | '+((L?LVL_CN:LVL_EN)[p.lvl]!=null?(L?LVL_CN:LVL_EN)[p.lvl]:'L'+p.lvl)+' | '+(T[p.ts]||p.ts)+' | '+(K[p.stk]!=null?K[p.stk]:p.stk)+' | '+(((p.oracle||[]).length?map(p.oracle,O):O.na))+' | '+(M[p.dom]||p.dom)+' | '+(p.selfref?(L?'是':'Yes'):(L?'否':'No'))+' |');
    }
  }
  return lines.join('\n');
}

function inject(file,lang,sectionTitle){
  let c=fs.readFileSync(file,'utf8');
  const START='<!-- PAPER-INDEX:START -->';
  const END='<!-- PAPER-INDEX:END -->';
  const block=START+'\n'+build(lang)+'\n'+END;
  if(c.includes(START)){
    c=c.replace(new RegExp(START+'[\\s\\S]*?'+END),block);
  }else{
    const anchor=lang==='cn'?'## 仓库结构':'## Repository Structure';
    c=c.replace(anchor,'## '+sectionTitle+'\n\n'+block+'\n\n'+anchor);
  }
  fs.writeFileSync(file,c);
}

inject(path.join(ROOT,'README.md'),'en','Paper Index ('+DB.length+')');
inject(path.join(ROOT,'README_CN.md'),'cn','论文索引（'+DB.length+' 篇）');
const n=DB.filter(p=>p.card).length;
console.log('rendered: '+n+' cards + '+(DB.length-n)+' table rows into both READMEs');

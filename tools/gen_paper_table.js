// Regenerates the paper index tables in README.md / README_CN.md from data/papers.json.
// Usage: node tools/gen_paper_table.js   (run from the repo root)
const fs=require('fs');
const path=require('path');
const ROOT=path.join(__dirname,'..');
const DB=JSON.parse(fs.readFileSync(path.join(ROOT,'data','papers.json'),'utf8'));

const SCENE_ORDER=['policy','action','reward','skill','constraint','world','design','reasoning','agentself','research'];
const SCENE_EN={policy:'Policy',action:'Action',reward:'Reward',skill:'Skill',constraint:'Constraint',world:'World',design:'Design',reasoning:'Reasoning',agentself:'Agent-Self',research:'Research'};
const SCENE_CN={policy:'策略',action:'动作',reward:'奖励',skill:'技能',constraint:'约束',world:'世界',design:'设计',reasoning:'推理',agentself:'自我',research:'研究'};
const DIR_EN={oneshot:'One-shot',loop:'Closed-loop',evo:'Evolutionary',skill:'Skill-accrual',multi:'Multi-agent',wm:'World-model',mem:'Memory'};
const DIR_CN={oneshot:'单次生成',loop:'闭环调整',evo:'进化搜索',skill:'技能沉淀',multi:'多智能体',wm:'世界模型',mem:'记忆上下文'};
const LVL_EN={0:'Frozen mechanism',1:'Mechanism self-evolves',2:'Adapts at runtime',3:'Weight training',4:'Recursive self-improvement'};
const LVL_CN={0:'机制冻结',1:'机制自进化',2:'运行时适应',3:'权重训练',4:'递归自我改进'};
const TS_EN={a:'Collects data + trains',b:'Collects data, no training',c:'Trains, no data collection',d:'Frozen at runtime'};
const TS_CN={a:'采集数据＋训练',b:'只采集数据，不训练',c:'只训练，不采集',d:'运行时全冻结'};
const STK_EN={0:'—',1:'Evidence feedback',2:'Verification feedback',3:'Data flywheel'};
const STK_CN={0:'—',1:'证据反馈',2:'验证反馈',3:'数据飞轮'};
const ORA_EN={sym:'Symbolic',sim:'Simulation',model:'Model',real:'Real-world',human:'Human',na:'—'};
const ORA_CN={sym:'符号',sim:'仿真',model:'模型',real:'真实环境',human:'人类',na:'—'};
const DOM_EN={robot:'Robotics',general:'General',front:'Frontend',swe:'Software',gui:'GUI',mc:'Minecraft',math:'Math',web:'Web',cad:'CAD',onto:'Ontology',drug:'Drug discovery',chip:'Chip',arch:'Architecture',law:'Legal',nlp:'NLP',multimodal:'Multimodal'};
const DOM_CN={robot:'机器人',general:'通用',front:'前端',swe:'软件工程',gui:'图形界面',mc:'Minecraft',math:'数学',web:'网页',cad:'CAD',onto:'本体',drug:'药物研发',chip:'芯片',arch:'体系结构',law:'法律',nlp:'NLP',multimodal:'多模态'};

const esc=s=>String(s||'').replace(/\|/g,'/');
const map=(vals,dic)=>(vals||[]).map(v=>dic[v]||v).join(', ');
const lvlName=(lvl,dic)=>dic[lvl]!=null?dic[lvl]:('L'+lvl);

function build(lang){
  const L=lang==='cn';
  const S=L?SCENE_CN:SCENE_EN, D=L?DIR_CN:DIR_EN, V=L?LVL_CN:LVL_EN, T=L?TS_CN:TS_EN,
        K=L?STK_CN:STK_EN, O=L?ORA_CN:ORA_EN, M=L?DOM_CN:DOM_EN;
  const lines=[];
  lines.push(L?'<!-- 论文索引（由 tools/gen_paper_table.js 生成，勿手改） -->':'<!-- Paper index (generated by tools/gen_paper_table.js — do not edit by hand) -->');
  lines.push(L?'共 **'+DB.length+' 篇**，单表列出，按场景归拢、更新能力降序排列。八个维度各占一列，含义见 [四维分类体系](#四维分类体系) 与 [附加-tag](#附加-tag)。'
              :'**'+DB.length+' papers** in a single table, clustered by scene and sorted by update capability within each. Each of the 8 dimensions gets its own column — see [The Taxonomy](#the-taxonomy) and [Additional Tags](#additional-tags).');
  lines.push('');
  const head=L?['#','论文','场景','方向','更新能力','运行时行为','反馈栈','Oracle','领域','自指闭环']
              :['#','Paper','Scene','Direction','Update Capability','Runtime Behavior','Feedback Stack','Oracle','Domain','Self-Ref'];
  lines.push('| '+head.join(' | ')+' |');
  lines.push('|'+'---|'.repeat(head.length));
  let idx=0;
  for(const s of SCENE_ORDER){
    const papers=DB.filter(p=>p.scenes[0]===s).sort((a,b)=>b.lvl-a.lvl||parseInt(b.id.slice(1))-parseInt(a.id.slice(1)));
    for(const p of papers){
      idx++;
      lines.push('| '+idx+' | ['+esc(p.n)+']('+esc(p.l)+') | '+map(p.scenes,S)+' | '+map(p.dirs,D)+' | '+lvlName(p.lvl,V)+' | '+(T[p.ts]||p.ts)+' | '+(K[p.stk]!=null?K[p.stk]:p.stk)+' | '+map(p.oracle,O)+' | '+(M[p.dom]||p.dom)+' | '+(p.selfref?(L?'是':'Yes'):(L?'否':'No'))+' |');
    }
  }
  return lines.join('\n');
}

function inject(file,lang,sectionTitle){
  let c=fs.readFileSync(file,'utf8');
  const START='<!-- PAPER-INDEX:START -->';
  const END='<!-- PAPER-INDEX:END -->';
  const block=START+'\n'+build(lang)+'\n'+END;
  if(c.includes(START)){
    c=c.replace(new RegExp(START+'[\\s\\S]*?'+END),block);
  }else{
    const anchor=lang==='cn'?'## 仓库结构':'## Repository Structure';
    c=c.replace(anchor,'## '+sectionTitle+'\n\n'+block+'\n\n'+anchor);
  }
  fs.writeFileSync(file,c);
}

inject(path.join(ROOT,'README.md'),'en','Paper Index ('+DB.length+')');
inject(path.join(ROOT,'README_CN.md'),'cn','论文索引（'+DB.length+' 篇）');
console.log('injected '+DB.length+' papers into both READMEs');
